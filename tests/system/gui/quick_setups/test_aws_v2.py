@pytest.fixture(name="fake_aws_v2_dump", scope="module")
def fixture_fake_aws_v2_dump(test_site: Site) -> Iterator[None]:
    """Fake the AWS v2 special agent used within Checkmk site.

    Quick setup performs validation of AWS connection.
    Faking the AWS agent bypasses such validations, which are 'out-of-scope' of UI tests.
    """
    fake_agent_aws_v2 = Path(__file__).parent / "fake_agent_aws_v2.py"
    aws_agent = get_source_file(test_site, cmk.plugins.aws_v2.special_agent.agent_aws_v2)
    backup_agent = str(aws_agent).replace(".py", ".py.bck")
    run(["cp", str(aws_agent), backup_agent], sudo=True)
    run(["cp", str(fake_agent_aws_v2), str(aws_agent)], sudo=True)
    yield
    if is_cleanup_enabled():
        run(["cp", str(backup_agent), str(aws_agent)], sudo=True)
        run(["rm", str(backup_agent)], sudo=True)


@pytest.fixture(name="aws_v2_qs_config_page")
def fixture_aws_v2_qs_config_page(
    fake_aws_v2_dump: None,  # noqa: ARG001  # Unused fixtures are needed for setup side effects
    dashboard_page: MainDashboard,
    test_site: Site,
) -> Iterator[AWSv2AddNewConfiguration]:
    """Navigate to the AWS v2 Quick setup page and add new configuration page"""
    configuration_name = "my_aws_v2_account"
    folder_details = AWSv2AddNewConfiguration.FolderDetails(
        name="aws_v2_folder",
        parent="Main",
        create_new=True,
    )
    aws_qs_config_page = AWSv2AddNewConfiguration(
        dashboard_page.page,
        configuration_name=configuration_name,
        folder_details=folder_details,
    )
    yield aws_qs_config_page
    aws_config_list_page = AWSv2ConfigurationList(aws_qs_config_page.page)
    activate = False
    # quick check; validation is performed in the test
    if aws_config_list_page.configuration_row(configuration_name).count() > 0:
        aws_config_list_page.delete_configuration(configuration_name)
        activate = True

    list_hosts_page = SetupHost(aws_config_list_page.page)
    # the quick setup could have failed before the folder gets created
    if list_hosts_page.folder_icon(folder_details.name).count() > 0:
        list_hosts_page.delete_folder(folder_details.name)
        activate = True

    if activate:  # only activate if we deleted the quick setup or folder
        list_hosts_page.activate_changes(test_site)


def test_minimal_configuration(
    aws_v2_qs_config_page: AWSv2AddNewConfiguration, test_site: Site
) -> None:
    """Validate setup of an AWS configuration using 'Quick setup: AWS v2'"""
    config_name = aws_v2_qs_config_page.configuration_name
    config_name_pattern = re.compile(config_name)
    host_name = "aws_v2_host"
    password_name = f"{config_name}_password"  # this is auto-generated by Checkmk

    # Stage 1
    aws_v2_qs_config_page.specify_stage_one_details(
        access_key="my_aws_access_key",
        access_password="my_aws_access_password",
    )

    aws_v2_qs_config_page.validate_button_text_and_goto_next_qs_stage(current_stage=1)

    # Stage 2
    aws_v2_qs_config_page.specify_stage_two_details(
        host_name,
        regions_to_monitor=["ap-south-1", "eu-central-1"],
        site_name=test_site.id,
    )

    aws_v2_qs_config_page.validate_button_text_and_goto_next_qs_stage(current_stage=2)

    # Stage 3
    aws_v2_qs_config_page.specify_stage_three_details(
        global_services={"Costs and usage (CE)": "Monitor service"},
        regional_services={"Elastic Compute Cloud (EC2)": "Do not monitor service"},
    )

    aws_v2_qs_config_page.validate_button_text_and_goto_next_qs_stage(current_stage=3)

    # Stage 4
    aws_v2_qs_config_page.click_test_configuration_button()
    expect(
        aws_v2_qs_config_page.main_area.locator().get_by_text("AWS services found!"),
        message="Expected AWS services to be found after the connection test!",
    ).to_be_visible()
    # wait for stage transition animation
    aws_v2_qs_config_page.page.wait_for_timeout(ANIMATION_TIMEOUT)
    aws_v2_qs_config_page.save_quick_setup()

    logger.info("Validate AWS v2 configuration is listed.")
    qs_list_page = aws_v2_qs_config_page.list_configuration_page()
    expect(
        qs_list_page.configuration_row(config_name),
        message="Expected the new AWS v2 Quick setup to be listed!",
    ).to_be_visible()

    logger.info("Validate AWS v2 folder and host is setup.")
    list_hosts_page = SetupHost(qs_list_page.page)
    list_hosts_page.click_and_wait(
        list_hosts_page.get_link(aws_v2_qs_config_page.folder_details.name),
        expected_locator=list_hosts_page.get_link(host_name),
    )

    logger.info("Validate AWS v2 rule is setup.")
    list_aws_rules_page = Ruleset(
        list_hosts_page.page, "Amazon Web Services (AWS) v2", "special_agents:aws_v2"
    )
    expect(
        list_aws_rules_page.rule_source(rule_id=0),
        message="Expected the AWS v2 rule to be created!",
    ).to_have_text(config_name_pattern)
    expect(
        list_aws_rules_page.get_link(config_name, exact=False),
        message="Expected the Quick setup to be linked on the rule page!",
    ).to_be_visible()

    logger.info("Validate AWS v2 password is setup.")
    list_passwords_page = Passwords(list_aws_rules_page.page)
    expect(
        list_passwords_page.password_source(password_name),
        message="Expected the AWS v2 password to be created!",
    ).to_have_text(config_name_pattern)
    expect(
        list_passwords_page.get_link(config_name, exact=False),
        message="Expected the Quick setup to be linked on the password page!",
    ).to_be_visible()

    if test_site.edition.is_community_edition():
        logger.info("Skipping DCD validation for Checkmk Community.")
    else:
        logger.info("Validate AWS v2 DCD connection is setup.")
        dcd_page = DCD(list_passwords_page.page)
        expect(
            dcd_page.connection_row(aws_v2_qs_config_page.configuration_name),
            message="Expected a DCD connection for the AWS v2 Quick setup to exist!",
        ).to_be_visible()
